import {katexStyles} from './katex-css.mjs';
import {uiAffordancesStyles} from './ui-affordances-css.mjs';
import {noteUiStyles} from './note-ui-css.mjs';
import {build} from 'esbuild';
import {uiLanguagePlugin} from './ui-language.mjs';
import {milkdownSlashPlugin} from './milkdown-slash.mjs';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
const result=await build({entryPoints:['src/whiteboard/entry.ts'],bundle:true,write:false,platform:'browser',target:'es2022',format:'iife',minify:true,legalComments:'none',plugins:[milkdownSlashPlugin(),uiLanguagePlugin()]});
const styles=await Promise.all(['structured-styles.css.html','editable-flow-styles.css.html','mcp-whiteboard-styles.css.html',"canvas-chrome.css.html","graph-canvas.css.html","whiteboard-interactions.css.html","paper-workbench.css.html"].map(p=>readFile('src/whiteboard/'+p,'utf8')));
styles.push(await readFile('src/whiteboard/resizable-panel.css.html','utf8'));
styles.push(await readFile('src/whiteboard/study-note-styles.css.html','utf8'));
styles.push(await readFile('src/whiteboard/card-selection.css.html','utf8'));
styles.push('<style>'+await readFile('src/shared/control-tooltip.css','utf8')+'</style>');
styles.push('<style>'+await uiAffordancesStyles()+'</style>');
styles.push(await readFile('src/whiteboard/compact-chrome.css.html','utf8'));
styles.push(await readFile('src/whiteboard/board-export-dialog.css.html','utf8'));
styles.unshift('<style>'+await noteUiStyles()+'</style>');
styles.unshift('<style>'+await katexStyles()+'</style>');
const base=await readFile('src/ui/wiki-graph.css','utf8');
const palette=await readFile('src/whiteboard/graph-palette.css','utf8');
const template=await readFile('src/ui/wiki-graph.html','utf8');
const html=template.replace('<!--GRAPH_STYLE-->',()=>'<style>'+base+'\n'+palette+'</style>'+styles.join('\n')).replace('<!--GRAPH_SCRIPT-->',()=>result.outputFiles[0].text.replaceAll('</script','<\\/script')).replace('<section class="map"','<section id="map" class="map"').replace('<script type="application/json" id="graph-data">','<script type="application/json" id="graph-pages"><!--GRAPH_PAGES--></script><script type="application/json" id="graph-data">');
await mkdir('dist/whiteboard',{recursive:true});await writeFile('dist/whiteboard/index.html',html);
