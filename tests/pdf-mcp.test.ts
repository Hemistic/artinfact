import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { InMemoryTransport } from '@modelcontextprotocol/sdk/inMemory.js';
import { createLayoutServer } from '../src/server/server.ts';
import { startReaderService } from '../src/server/reader-service.ts';
import { PdfStateStore } from '../src/server/pdf-store.ts';

test('PDF entrypoints advertise scoped iframe CSP, hide local access URLs, and expose annotation tools only to the app', async () => {
  const root = await mkdtemp(join(tmpdir(), 'codex-pdf-mcp-'));
  await writeFile(join(root, 'reader.html'), '<title>Reader</title>');
  await writeFile(join(root, 'reader-local.html'), '<title>Packaged Reader</title>');
  const service = await startReaderService(root);
  const store = new PdfStateStore(join(root, 'state'));
  const server = createLayoutServer({ workspace: root, html: '<html></html>', pdf: { service, store, html: '<html lang="zh"><title>PDF</title></html>' } });
  const [a, b] = InMemoryTransport.createLinkedPair();
  const client = new Client({ name: 'pdf-contract-check', version: '1' });
  await server.connect(a); await client.connect(b);
  try {
    const tools = (await client.listTools()).tools;
    const tool = tools.find(value => value.name === 'pdf_open')!;
    assert.ok(tool);
    assert.deepEqual((tool._meta?.['openai/ui'] as { entrypoints: unknown[] }).entrypoints, [{ type: 'thread' }, { type: 'file', extensions: ['pdf', 'md'] }]);
    const sidebar = tools.find(value => value.name === 'pdf_sidebar')!;
    assert.deepEqual((sidebar._meta?.['openai/ui'] as { entrypoints: unknown[] }).entrypoints, [{ type: 'global' }]);
    const globalApps = tools.filter(value => (value._meta?.['openai/ui'] as { entrypoints?: { type: string }[] } | undefined)?.entrypoints?.some(entry => entry.type === 'global'));
    assert.deepEqual(globalApps.map(value => value.name), ['pdf_sidebar']);
    assert.equal(sidebar.title, 'Artinfact');
    assert.equal(tool.title, 'Artinfact');
    assert.equal(client.getServerVersion()?.title, 'Artinfact');
    for (const name of ['pdf_sidebar', 'pdf_open_path', 'pdf_state_read', 'pdf_state_update', 'pdf_document_read', 'pdf_runtime_read', 'pdf_preferences_read', 'pdf_preferences_update', 'pdf_export_start', 'pdf_export_upload', 'pdf_export_finish', 'pdf_export_read', 'pdf_export_release']) assert.deepEqual((tools.find(value => value.name === name)?._meta?.ui as { visibility: string[] }).visibility, ['app']);
    const result = await client.callTool({ name: 'pdf_open', arguments: {} });
    for (const tool of tools.filter(t => t.name.startsWith('pdf_mineru_'))) assert.deepEqual((tool._meta?.ui as { visibility: string[] }).visibility, ['app']);
    for (const name of ['pdf_structure_list', 'pdf_structure_read', 'pdf_markdown_read']) assert.ok(tools.some(t => t.name === name));
    const settings = await client.callTool({ name: 'pdf_mineru_settings_update', arguments: { baseUrl: 'http://127.0.0.1:4197', clientKey: 'contract-test-secret' } });
    assert.doesNotMatch(JSON.stringify(settings), /contract-test-secret/);
    assert.equal(result.isError, undefined);
    assert.doesNotMatch(JSON.stringify([result.content, result.structuredContent]), /127\.0\.0\.1/);
    assert.equal((result._meta?.pdfReader as { baseUrl: string }).baseUrl, service.baseUrl);
    const resource = await client.readResource({ uri: (tool._meta?.ui as { resourceUri: string }).resourceUri });
    assert.equal(resource.contents[0].mimeType, 'text/html;profile=mcp-app');
    assert.doesNotMatch((tool._meta?.ui as { resourceUri: string }).resourceUri, new RegExp(new URL(service.origin).port + '$'));
    assert.doesNotMatch(JSON.stringify(resource.contents[0]._meta), /127\.0\.0\.1/);
    const legacy = await client.readResource({ uri: 'ui://codex-work-layout/pdf/0.4.1/12345' });
    assert.equal(legacy.contents[0].mimeType, 'text/html;profile=mcp-app');
    const previousSidebar = await client.readResource({ uri: 'ui://codex-work-layout/pdf/0.4.5/sidebar' });
    const lastSidebar = await client.readResource({ uri: 'ui://codex-work-layout/pdf/0.4.6/sidebar' });
    assert.ok('text' in lastSidebar.contents[0]);
    assert.ok('text' in previousSidebar.contents[0]);
    assert.match(previousSidebar.contents[0].text, /data-surface="sidebar"/);
    const runtime = await client.callTool({ name: 'pdf_runtime_read', arguments: { offset: 0, length: 100 } });
    assert.doesNotMatch(JSON.stringify(runtime.content), /Packaged Reader/);
    assert.equal((runtime._meta?.readerRuntime as { text: string }).text, '<title>Packaged Reader</title>');
    const id = 'a'.repeat(64);
    await client.callTool({ name: 'pdf_state_update', arguments: { documentId: id, patch: { annotations: [{ id: 'A', text: 'quote', type: 'highlight' }] } } });
    const state = await client.callTool({ name: 'pdf_state_read', arguments: { documentId: id } });
    assert.doesNotMatch(JSON.stringify(state.content), /quote/);
    assert.equal((state._meta?.pdfState as { annotations: unknown[] }).annotations.length, 1);
  } finally { await client.close(); await server.close(); await service.close(); }
});
